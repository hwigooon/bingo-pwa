function normalize(value: string): string {
  return value.toLocaleLowerCase("ko-KR").replace(/\s+/g, "");
}

export const TOPIC_LABELS = Object.keys(PRESETS);

export function getLocalTopicWords(topic: string): string[] {
  const normalizedTopic = normalize(topic);
  if (!normalizedTopic) return [];

  const matchedKey = Object.entries(ALIASES).find(([, aliases]) =>
    aliases.some((alias) => {
      const normalizedAlias = normalize(alias);
      return normalizedTopic.includes(normalizedAlias) || normalizedAlias.includes(normalizedTopic);
    }),
  )?.[0];

  return matchedKey ? [...(PRESETS[matchedKey] ?? [])] : [];
}
